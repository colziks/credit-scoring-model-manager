"""Influence of noise in the features on CatBoost and TabPFN-2.5.

Noise is applied to the training sample AND to validation / test objects (the data itself is noisy):
  num: x -> x + sigma * std_train(x) * N(0, 1) for every numeric feature
  cat: with probability p the value of a categorical feature is replaced by a random value
       drawn from its distribution in the training sample
The noise is generated by the same code and the same random seeds for both models.

Regime: N, share of defaults, seeds (default N=5000, natural share, seeds 0 1 2).
Metrics on the same 10 000 validation / 10 000 test objects as in the main experiment:
  type-I error E_I at q = 5, 10, 20 % (threshold from validation) and ROC AUC (test).

Run (cmd), CatBoost, about 1 min per run:
  python src\\noise_experiment.py --model catboost
Run (Colab, T4), TabPFN-2.5:
  python noise_experiment.py --model tabpfn --splits noise_data
Report (needs the csv files of both models in results\\noise):
  python src\\noise_experiment.py --report
"""
import argparse
import glob
import json
import os
import time

import numpy as np
import pandas as pd

SUB = 10000
QS = (0.05, 0.10, 0.20)


def subset_idx(n_total, k, part):
    seed = {"val": 101, "test": 202}[part]
    return np.sort(np.random.default_rng(seed).permutation(n_total)[:k])


def e1(reject, y):
    pos = y == 1
    return float(np.sum(~reject & pos) / pos.sum())


def add_noise(tr, va, te, num, cat, kind, level, seed):
    """returns noisy copies of (train, val, test); the noise statistics are taken from the clean train"""
    tr, va, te = tr.copy(), va.copy(), te.copy()
    if kind == "none":
        return tr, va, te
    rng = np.random.default_rng(seed * 100003 + int(level * 1000) + (7 if kind == "cat" else 0))
    if kind == "num":
        sd = tr[num].std(ddof=0).to_numpy(float)
        for df in (tr, va, te):
            arr = df[num].to_numpy(float)
            arr = arr + level * sd * rng.standard_normal(arr.shape)
            df[num] = arr
    elif kind == "cat":
        pools = {c: tr[c].to_numpy().copy() for c in cat}
        for df in (tr, va, te):
            for c in cat:
                mask = rng.random(len(df)) < level
                if mask.any():
                    df.loc[mask, c] = rng.choice(pools[c], size=int(mask.sum()))
    else:
        raise ValueError(kind)
    return tr, va, te


def fit_predict(model, tr, va, te, feats, cat, seed):
    ytr = tr["flag"].to_numpy()
    if model == "catboost":
        from catboost import CatBoostClassifier
        Xtr, Xva, Xte = tr[feats].copy(), va[feats].copy(), te[feats].copy()
        for X in (Xtr, Xva, Xte):
            for c in cat:
                X[c] = X[c].astype("int64")
        m = CatBoostClassifier(iterations=500, learning_rate=0.05, depth=6, random_seed=seed,
                               verbose=False, cat_features=cat)
        m.fit(Xtr, ytr)
        return m.predict_proba(Xva)[:, 1], m.predict_proba(Xte)[:, 1]
    if model == "tabpfn":
        from tabpfn import TabPFNClassifier
        from tabpfn.constants import ModelVersion
        clf = TabPFNClassifier.create_default_for_version(ModelVersion.V2_5)
        try:
            clf.set_params(categorical_features_indices=[feats.index(c) for c in cat])
        except Exception as e:                                   # keep going, the check against the main run will show
            print("   ВНИМАНИЕ: категориальные признаки не заданы:", e)
        clf.fit(tr[feats].to_numpy(np.float32), ytr)
        return (clf.predict_proba(va[feats].to_numpy(np.float32))[:, 1],
                clf.predict_proba(te[feats].to_numpy(np.float32))[:, 1])
    raise ValueError(model)


def run(args):
    fs = json.load(open(os.path.join(args.splits, "feature_sets.json"), encoding="utf-8"))
    feats = fs["feature_sets"]["all"]
    cat = [c for c in fs["categorical"] if c in feats]
    num = [c for c in feats if c not in cat]
    val = pd.read_parquet(os.path.join(args.splits, "val.parquet"))
    test = pd.read_parquet(os.path.join(args.splits, "test.parquet"))
    va0 = val.iloc[subset_idx(len(val), SUB, "val")][feats + ["flag"]].reset_index(drop=True)
    te0 = test.iloc[subset_idx(len(test), SUB, "test")][feats + ["flag"]].reset_index(drop=True)
    yv, yt = va0["flag"].to_numpy(), te0["flag"].to_numpy()

    out_dir = os.path.join(args.results, "noise")
    os.makedirs(out_dir, exist_ok=True)
    csv_path = os.path.join(out_dir, "noise_results_%s.csv" % args.model)
    done = set()
    if os.path.exists(csv_path):
        d = pd.read_csv(csv_path)
        done = set(zip(d.seed, d.kind, d.level))

    from sklearn.metrics import roc_auc_score
    configs = [("none", 0.0)] + [("num", s) for s in args.num_levels] + [("cat", p) for p in args.cat_levels]
    total = len(configs) * len(args.seeds)
    k = 0
    for seed in args.seeds:
        tr0 = pd.read_parquet(os.path.join(args.splits, "subsamples", f"train_n{args.n}_p{args.rate}_s{seed}.parquet"))[feats + ["flag"]]
        for kind, level in configs:
            k += 1
            if (seed, kind, level) in done:
                print("[%d/%d] пропуск (уже посчитано): seed=%d %s %g" % (k, total, seed, kind, level))
                continue
            t0 = time.time()
            tr, va, te = add_noise(tr0, va0, te0, num, cat, kind, level, seed)
            pv, pt = fit_predict(args.model, tr, va, te, feats, cat, seed)
            row = dict(model=args.model, N=args.n, rate=args.rate, seed=seed, kind=kind, level=level,
                       auc=roc_auc_score(yt, pt), seconds=round(time.time() - t0, 1))
            for q in QS:
                t = np.quantile(pv, 1 - q)
                row["E_I_q%02d" % round(q * 100)] = e1(pt >= t, yt)
            pd.DataFrame([row]).to_csv(csv_path, mode="a", header=not os.path.exists(csv_path), index=False)
            print("[%d/%d] seed=%d %-4s %-5g  E_I(q=10%%)=%.3f  AUC=%.3f  (%.0f с)" % (
                k, total, seed, kind, level, row["E_I_q10"], row["auc"], row["seconds"]))
    print("\nГотово:", csv_path)


def report(args):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    files = glob.glob(os.path.join(args.results, "noise", "noise_results_*.csv"))
    if not files:
        raise SystemExit("нет файлов results\\noise\\noise_results_*.csv")
    d = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    names = {"catboost": "CatBoost", "tabpfn": "TabPFN-2.5"}
    d["model"] = d["model"].map(names)
    base = d[d.kind == "none"].set_index(["model", "seed"])
    rows = []
    for (m, kind, level), g in d[d.kind != "none"].groupby(["model", "kind", "level"]):
        dd = []
        for _, r in g.iterrows():
            if (m, r.seed) in base.index:
                b = base.loc[(m, r.seed)]
                dd.append((r.E_I_q10 - b.E_I_q10, r.auc - b.auc))
        dd = np.array(dd)
        rows.append(dict(модель=m, шум=kind, уровень=level, запусков=len(g),
                         E_I_q10=round(g.E_I_q10.mean(), 3), E_I_мин=round(g.E_I_q10.min(), 3), E_I_макс=round(g.E_I_q10.max(), 3),
                         рост_E_I=round(dd[:, 0].mean(), 3) if len(dd) else np.nan,
                         AUC=round(g.auc.mean(), 3), падение_AUC=round(-dd[:, 1].mean(), 3) if len(dd) else np.nan))
    t = pd.DataFrame(rows)
    b = d[d.kind == "none"].groupby("model")[["E_I_q05", "E_I_q10", "E_I_q20", "auc"]].mean().round(3)
    print("Без шума (среднее по запускам):")
    print(b.to_string())
    print("\nС шумом (рост_E_I и падение_AUC относительно той же модели без шума, парно по запускам):")
    print(t.to_string(index=False))
    t.to_csv(os.path.join(args.results, "noise", "noise_summary.csv"), index=False, encoding="utf-8-sig")

    fig, axes = plt.subplots(1, 2, figsize=(7, 3.2), sharey=True)
    for ax, kind, xl in ((axes[0], "num", "Шум в числовых признаках, $\\sigma$"), (axes[1], "cat", "Замена категорий, $p$")):
        for m, mk, ls in (("TabPFN-2.5", "o", "-"), ("CatBoost", "s", "--")):
            g0 = d[(d.model == m) & (d.kind == "none")]
            g1 = d[(d.model == m) & (d.kind == kind)]
            if g0.empty or g1.empty:
                continue
            lv = [0.0] + sorted(g1.level.unique())
            vals = [g0.E_I_q10.to_numpy()] + [g1[g1.level == l].E_I_q10.to_numpy() for l in lv[1:]]
            mean = [v.mean() * 100 for v in vals]
            err = [[(v.mean() - v.min()) * 100 for v in vals], [(v.max() - v.mean()) * 100 for v in vals]]
            ax.errorbar(lv, mean, yerr=err, marker=mk, ls=ls, color="black", ms=4, lw=1.1, capsize=2, label=m)
        ax.set_xlabel(xl)
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("Ошибка I рода при $q$ = 10%, %")
    axes[0].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(args.figures, "fig_noise.png"), dpi=200)
    print("\nСохранено: results\\noise\\noise_summary.csv, figures\\fig_noise.png")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", choices=["catboost", "tabpfn"])
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--n", type=int, default=5000)
    ap.add_argument("--rate", default="nat")
    ap.add_argument("--seeds", nargs="+", type=int, default=[0, 1, 2])
    ap.add_argument("--num-levels", nargs="+", type=float, default=[0.25, 0.5, 1.0])
    ap.add_argument("--cat-levels", nargs="+", type=float, default=[0.1, 0.25, 0.5])
    ap.add_argument("--splits", default="data/splits")
    ap.add_argument("--figures", default="figures")
    ap.add_argument("--results", default="results")
    args, unknown = ap.parse_known_args(argv)   # ignores the service arguments added by Jupyter / Colab
    if unknown:
        print("Проигнорированы лишние аргументы:", unknown)
    if args.report:
        os.makedirs(args.figures, exist_ok=True)
        report(args)
    elif args.model:
        run(args)
    else:
        ap.error("укажите --model catboost|tabpfn или --report")


if __name__ == "__main__":
    main()
